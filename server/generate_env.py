import base64
from binascii import Error as Base64Error
from pathlib import Path

from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parent.parent
CLIENT_ENV = ROOT / "client" / ".env"
SERVER_ENV = Path(__file__).with_name(".env")

POSTGRES_USER = "license"
POSTGRES_PASSWORD = "license"
POSTGRES_DB = "license"


def main() -> None:
    if SERVER_ENV.exists():
        raise SystemExit(f"{SERVER_ENV} already exists; delete it to regenerate")
    if not CLIENT_ENV.exists():
        raise SystemExit(f"{CLIENT_ENV} not found; run client/generate_env.py first")

    client = dotenv_values(CLIENT_ENV)
    key = client.get("DEVICE_ENCRYPTION_KEY")
    if not key:
        raise SystemExit(f"DEVICE_ENCRYPTION_KEY is missing in {CLIENT_ENV}")

    try:
        raw_key = base64.b64decode(key, validate=True)
    except (Base64Error, ValueError) as exc:
        raise SystemExit(f"DEVICE_ENCRYPTION_KEY is not valid base64: {exc}") from exc
    if len(raw_key) != 64:
        raise SystemExit(f"DEVICE_ENCRYPTION_KEY must be 64 bytes, got {len(raw_key)}")

    content = (
        "# Generated by generate_env.py from client/.env. Do not commit this file.\n"
        f"DEVICE_ENCRYPTION_KEY={key}\n"
        f"DATABASE_URL=postgresql+asyncpg://{POSTGRES_USER}:{POSTGRES_PASSWORD}"
        f"@localhost:5432/{POSTGRES_DB}\n"
        f"POSTGRES_USER={POSTGRES_USER}\n"
        f"POSTGRES_PASSWORD={POSTGRES_PASSWORD}\n"
        f"POSTGRES_DB={POSTGRES_DB}\n"
    )
    SERVER_ENV.write_text(content, encoding="utf-8")
    SERVER_ENV.chmod(0o600)
    print(f"Wrote {SERVER_ENV} (key taken from {CLIENT_ENV})")


if __name__ == "__main__":
    main()
